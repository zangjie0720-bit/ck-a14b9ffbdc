/* ================= 日期工具 ================= */
function parse(s) {
  var p = s.split('-');
  return new Date(+p[0], +p[1] - 1, +p[2]);
}
function pad(n) { return n < 10 ? '0' + n : '' + n; }
function fmt(d) {
  return d.getFullYear() + '-' + pad(d.getMonth() + 1) + '-' + pad(d.getDate());
}
function addDays(d, n) {
  return new Date(d.getFullYear(), d.getMonth(), d.getDate() + n);
}
function weekIdx(s) {
  return Math.floor((parse(s) - parse(W0)) / 604800000);
}
function isTrip(s) {
  return s >= TRIP_S && s <= TRIP_E;
}

/* 全部日期 */
var ALL = (function () {
  var out = [], c = parse(START), e = parse(END);
  while (c <= e) { out.push(fmt(c)); c = addDays(c, 1); }
  return out;
})();

/* ================= 每日任务生成 ================= */
function buildTasks(s) {
  var w = parse(s).getDay();
  var wk = WEEKS[weekIdx(s)];
  var out = [];
  if (!wk) return out;

  /* 旅行期间：备考减量，整理不规划 */
  if (isTrip(s)) {
    out.push({ c: 'm', t: '旅途中：就寝不超过 01:00，别连续两天熬夜', m: '底线' });
    out.push({ c: 's', t: '轻量 15 分钟：刷 1 组选择题（判断 / 单选 / 多选各 10 题）', m: '15 分' });
    out.push({ c: 'm', t: '睡前 30 分钟放下手机，别在床上刷到停不下来', m: '—' });
    return out;
  }

  out.push({ c: 'm', t: '就寝目标 ' + wk.sleepTarget + ' ｜ 22:30 起手机移出卧室充电', m: '就寝' });
  out.push({ c: 'm', t: '07:30 固定起床，起床后立刻拉开窗帘见光 10 分钟', m: '起床' });

  if (w >= 1 && w <= 5) {
    var i = w - 1;
    if (wk.study.wd[i]) out.push({ c: 's', t: wk.study.wd[i], m: '45 分' });
    if (wk.tidy.wd[i] && wk.tidy.wd[i] !== '旅途中：不安排') {
      out.push({ c: 'z', t: wk.tidy.wd[i], m: '20 分' });
    }
  } else {
    var j = (w === 6) ? 0 : 1;
    if (wk.study.we[j]) out.push({ c: 's', t: wk.study.we[j], m: '2 小时' });
    if (wk.tidy.we[j]) out.push({ c: 'z', t: wk.tidy.we[j], m: '3 小时' });
  }
  return out;
}

/* 预生成，避免每次渲染重复计算 */
var TASK_MAP = {};
ALL.forEach(function (s) { TASK_MAP[s] = buildTasks(s); });

function tasksOf(s) {
  return TASK_MAP[s] || [];
}

